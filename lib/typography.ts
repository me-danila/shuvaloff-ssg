/**
 * Типографика русского текста для длинных текстовых блоков (политика, оферты).
 *
 * Тексты хранятся в data/* обычными строками — читаемыми и правимыми по
 * согласованному юристами документу. Неразрывные пробелы навешиваются здесь,
 * при рендере, чтобы в источнике не было невидимых символов.
 *
 * Все правила перечисляют кириллицу явным классом символов: \w и \b в JS
 * учитывают только ASCII, поэтому на русском тексте они не срабатывают.
 */

const LETTER = "A-Za-zА-Яа-яЁё";

/** Однобуквенные и двухбуквенные слова (предлоги, союзы) не остаются в конце строки. */
const SHORT_WORD = new RegExp(`(^|[\\s("«])([${LETTER}]{1,2})[ \\t]+`, "g");

/** Сокращение с точкой держится вместе с тем, к чему относится: «ул. Моховая». */
const ABBREVIATION =
    /(^|[\s("«])(ул|д|стр|пом|корп|кв|г|гг|п|пп|ст|им)\.[ \t]+/g;

/** Номер не отрывается от своего значения: «№ 152-ФЗ». */
const NUMBER_SIGN = /№[ \t]+/g;

/** Число не отрывается от следующего слова: «30 дней». */
const NUMBER_UNIT = new RegExp(`(\\d)[ \\t]+(?=[${LETTER}])`, "g");

/** Тире не начинает строку — перед ним неразрывный пробел. */
const EM_DASH = /[ \t]+—/g;

const NBSP = "\u00A0";

export function nbsp(text: string): string {
    return (
        text
            // два прохода: у соседних коротких слов («и в случае») совпадения
            // перекрываются, и один проход захватывает только первое из пары
            .replace(SHORT_WORD, `$1$2${NBSP}`)
            .replace(SHORT_WORD, `$1$2${NBSP}`)
            .replace(ABBREVIATION, `$1$2.${NBSP}`)
            .replace(NUMBER_SIGN, `№${NBSP}`)
            .replace(NUMBER_UNIT, `$1${NBSP}`)
            .replace(EM_DASH, `${NBSP}—`)
    );
}
